import type { AdminAction, ColumnDef, Engine, ForeignKeyDef, SchemaChange, SchemaOp } from '@shared/types'
import { ENGINES } from '@shared/engines'
import {
  bigqueryDialect,
  clickhouseDialect,
  cqlDialect,
  duckdbDialect,
  mssqlDialect,
  mysqlDialect,
  pgDialect,
  snowflakeDialect,
  sqliteDialect,
  tableRef,
  type Dialect
} from './sql'

const DIALECTS: Partial<Record<Engine, Dialect>> = {
  postgres: pgDialect,
  mysql: mysqlDialect,
  sqlite: sqliteDialect,
  mssql: mssqlDialect,
  duckdb: duckdbDialect,
  clickhouse: clickhouseDialect,
  snowflake: snowflakeDialect,
  bigquery: bigqueryDialect,
  cassandra: cqlDialect
}

function dialectFor(engine: Engine): Dialect {
  const d = DIALECTS[engine]
  if (!d) throw new Error(`${ENGINES[engine].label} does not use SQL for this.`)
  return d
}

/** Shown in previews instead of the real password. */
export const MASK = '********'

const lit = (v: string) => `'${v.replace(/'/g, "''")}'`
/** N'...' keeps non-ASCII text intact in SQL Server literals. */
const nlit = (v: string) => `N${lit(v)}`

/** Reject identifiers the user left blank before they turn into broken SQL. */
function required(value: string, what: string): string {
  if (!value.trim()) throw new Error(`${what} cannot be empty.`)
  return value.trim()
}

function columnSql(engine: Engine, d: Dialect, c: ColumnDef, inlinePk: boolean, seqName?: string): string {
  const parts = [d.quote(required(c.name, 'Column name')), required(c.type, `Type of "${c.name}"`)]
  if (c.autoIncrement && engine === 'mssql') parts.push('IDENTITY(1,1)')
  if (inlinePk) {
    // SQLite only: AUTOINCREMENT must sit on an inline INTEGER PRIMARY KEY.
    parts.push('PRIMARY KEY')
    if (c.autoIncrement) parts.push('AUTOINCREMENT')
  }
  if (!c.nullable && !inlinePk) parts.push('NOT NULL')
  if (c.autoIncrement && engine === 'duckdb' && seqName) parts.push(`DEFAULT nextval('${seqName.replace(/'/g, "''")}')`)
  else if (c.defaultValue !== null && c.defaultValue !== '') parts.push(`DEFAULT ${c.defaultValue}`)
  if (c.autoIncrement && engine === 'postgres') parts.push('GENERATED BY DEFAULT AS IDENTITY')
  if (c.autoIncrement && engine === 'mysql') parts.push('AUTO_INCREMENT')
  if (c.comment && engine === 'mysql') parts.push(`COMMENT ${lit(c.comment)}`)
  return parts.join(' ')
}

function fkSql(engine: Engine, d: Dialect, fk: ForeignKeyDef, schema: string): string {
  const cols = fk.columns.map(d.quote).join(', ')
  const refTable = required(fk.refTable, 'Referenced table')
  // SQLite foreign keys can't cross attached databases, and it rejects a qualified name here.
  const ref = engine === 'sqlite' ? d.quote(refTable) : tableRef(d, fk.refSchema || schema, refTable)
  const refCols = fk.refColumns.map(d.quote).join(', ')
  if (!fk.columns.length || !fk.refColumns.length) throw new Error('A foreign key needs columns on both sides.')
  const name = fk.name.trim() ? `CONSTRAINT ${d.quote(fk.name.trim())} ` : ''
  // DuckDB accepts only the default (restrict) referential actions.
  const actions = engine === 'duckdb' ? '' : ` ON UPDATE ${fk.onUpdate} ON DELETE ${fk.onDelete}`
  return `${name}FOREIGN KEY (${cols}) REFERENCES ${ref} (${refCols})${actions}`
}

function createTable(engine: Engine, d: Dialect, ref: string, schema: string, table: string, op: Extract<SchemaOp, { op: 'createTable' }>) {
  if (op.columns.length === 0) throw new Error('A table needs at least one column.')
  const pk = op.columns.filter((c) => c.isPrimaryKey)
  const sqliteInlinePk = engine === 'sqlite' && pk.length === 1 && pk[0].autoIncrement
  // DuckDB has no auto-increment keyword; a sequence plus DEFAULT nextval does the job.
  const sequences = engine === 'duckdb' ? op.columns.filter((c) => c.autoIncrement).map((c) => ({ col: c, name: `${table}_${c.name}_seq` })) : []
  const seqOf = (c: ColumnDef) => sequences.find((s) => s.col === c)?.name
  const lines = op.columns.map((c) => columnSql(engine, d, c, sqliteInlinePk && c === pk[0], seqOf(c)))
  if (pk.length && !sqliteInlinePk) lines.push(`PRIMARY KEY (${pk.map((c) => d.quote(c.name)).join(', ')})`)
  for (const fk of op.foreignKeys) lines.push(fkSql(engine, d, fk, schema))
  const seqSql = sequences.map((s) => `CREATE SEQUENCE IF NOT EXISTS ${tableRef(d, schema, s.name)}`)
  return [...seqSql, `CREATE TABLE ${ref} (\n  ${lines.join(',\n  ')}\n)`]
}

/** Postgres and DuckDB change one attribute per clause, so emit only what actually changed. */
function alterPerClause(engine: Engine, d: Dialect, ref: string, from: ColumnDef, to: ColumnDef): string[] {
  const out: string[] = []
  let name = from.name
  if (to.name !== from.name) {
    out.push(`ALTER TABLE ${ref} RENAME COLUMN ${d.quote(from.name)} TO ${d.quote(required(to.name, 'Column name'))}`)
    name = to.name
  }
  const col = d.quote(name)
  if (to.type !== from.type) {
    out.push(`ALTER TABLE ${ref} ALTER COLUMN ${col} TYPE ${to.type} USING ${col}::${to.type}`)
  }
  if (to.nullable !== from.nullable) {
    out.push(`ALTER TABLE ${ref} ALTER COLUMN ${col} ${to.nullable ? 'DROP' : 'SET'} NOT NULL`)
  }
  if ((to.defaultValue ?? '') !== (from.defaultValue ?? '')) {
    out.push(
      to.defaultValue
        ? `ALTER TABLE ${ref} ALTER COLUMN ${col} SET DEFAULT ${to.defaultValue}`
        : `ALTER TABLE ${ref} ALTER COLUMN ${col} DROP DEFAULT`
    )
  }
  if ((to.comment ?? '') !== (from.comment ?? '')) {
    out.push(`COMMENT ON COLUMN ${ref}.${col} IS ${to.comment ? lit(to.comment) : 'NULL'}`)
  }
  return out
}

/** SQL Server keeps defaults as named constraints; find and drop whichever one the column has. */
function mssqlDropDefault(schema: string, table: string, column: string): string {
  const object = nlit(`${mssqlDialect.quote(schema)}.${mssqlDialect.quote(table)}`)
  const ref = `${mssqlDialect.quote(schema)}.${mssqlDialect.quote(table)}`.replace(/'/g, "''")
  return (
    `DECLARE @df sysname; SELECT @df = d.name FROM sys.default_constraints d ` +
    `JOIN sys.columns c ON c.default_object_id = d.object_id ` +
    `WHERE d.parent_object_id = OBJECT_ID(${object}) AND c.name = ${nlit(column)}; ` +
    `IF @df IS NOT NULL EXEC(N'ALTER TABLE ${ref} DROP CONSTRAINT [' + @df + N']')`
  )
}

function alterMssql(d: Dialect, schema: string, table: string, ref: string, from: ColumnDef, to: ColumnDef): string[] {
  const out: string[] = []
  let name = from.name
  if (to.name !== from.name) {
    const target = `${schema}.${table}.${from.name}`
    out.push(`EXEC sp_rename ${nlit(target)}, ${nlit(required(to.name, 'Column name'))}, 'COLUMN'`)
    name = to.name
  }
  // ALTER COLUMN restates type and nullability together.
  if (to.type !== from.type || to.nullable !== from.nullable) {
    out.push(`ALTER TABLE ${ref} ALTER COLUMN ${d.quote(name)} ${to.type} ${to.nullable ? 'NULL' : 'NOT NULL'}`)
  }
  if ((to.defaultValue ?? '') !== (from.defaultValue ?? '')) {
    out.push(mssqlDropDefault(schema, table, name))
    if (to.defaultValue) out.push(`ALTER TABLE ${ref} ADD DEFAULT ${to.defaultValue} FOR ${d.quote(name)}`)
  }
  if ((to.comment ?? '') !== (from.comment ?? '')) {
    throw new Error('Column comments on SQL Server are extended properties; edit them in the SQL editor.')
  }
  return out
}

function alterColumn(engine: Engine, d: Dialect, change: SchemaChange, ref: string, from: ColumnDef, to: ColumnDef): string[] {
  switch (engine) {
    case 'postgres':
    case 'duckdb':
      return alterPerClause(engine, d, ref, from, to)
    case 'mysql':
      // MySQL restates the whole column; CHANGE also covers a rename.
      return [`ALTER TABLE ${ref} CHANGE COLUMN ${d.quote(from.name)} ${columnSql(engine, d, to, false)}`]
    case 'mssql':
      return alterMssql(d, change.schema, change.table, ref, from, to)
    case 'sqlite': {
      const onlyRename =
        to.type === from.type && to.nullable === from.nullable && (to.defaultValue ?? '') === (from.defaultValue ?? '')
      if (!onlyRename) {
        throw new Error(`SQLite can only rename "${from.name}". Changing its type, nullability or default means recreating the table.`)
      }
      return to.name === from.name
        ? []
        : [`ALTER TABLE ${ref} RENAME COLUMN ${d.quote(from.name)} TO ${d.quote(required(to.name, 'Column name'))}`]
    }
    default:
      throw new Error(`Altering columns is not available for ${ENGINES[engine].label}.`)
  }
}

function opSql(engine: Engine, d: Dialect, change: SchemaChange, op: SchemaOp): string[] {
  const ref = tableRef(d, change.schema, required(change.table, 'Table name'))
  switch (op.op) {
    case 'createTable':
      return createTable(engine, d, ref, change.schema, change.table, op)
    case 'addColumn':
      // SQL Server's ALTER TABLE ... ADD takes no COLUMN keyword.
      return [`ALTER TABLE ${ref} ADD ${engine === 'mssql' ? '' : 'COLUMN '}${columnSql(engine, d, op.column, false)}`]
    case 'dropColumn':
      return engine === 'mssql'
        ? [mssqlDropDefault(change.schema, change.table, op.name), `ALTER TABLE ${ref} DROP COLUMN ${d.quote(op.name)}`]
        : [`ALTER TABLE ${ref} DROP COLUMN ${d.quote(op.name)}`]
    case 'alterColumn':
      return alterColumn(engine, d, change, ref, op.from, op.to)
    case 'addIndex': {
      if (!op.index.columns.length) throw new Error('An index needs at least one column.')
      const cols = op.index.columns.map(d.quote).join(', ')
      // SQLite puts the schema on the index name; the others take it from the table.
      const name = d.quote(required(op.index.name, 'Index name'))
      const target = engine === 'sqlite' ? `${d.quote(change.schema)}.${name}` : name
      const on = engine === 'sqlite' ? d.quote(change.table) : ref
      return [`CREATE ${op.index.unique ? 'UNIQUE ' : ''}INDEX ${target} ON ${on} (${cols})`]
    }
    case 'dropIndex':
      return engine === 'mysql' || engine === 'mssql'
        ? [`DROP INDEX ${d.quote(op.name)} ON ${ref}`]
        : [`DROP INDEX ${d.quote(change.schema)}.${d.quote(op.name)}`]
    case 'addForeignKey':
      if (engine === 'sqlite' || engine === 'duckdb') {
        throw new Error(`${ENGINES[engine].label} can only define foreign keys when a table is created.`)
      }
      return [`ALTER TABLE ${ref} ADD ${fkSql(engine, d, op.fk, change.schema)}`]
    case 'dropForeignKey':
      if (engine === 'sqlite' || engine === 'duckdb') {
        throw new Error(`${ENGINES[engine].label} cannot drop a foreign key without recreating the table.`)
      }
      return engine === 'mysql'
        ? [`ALTER TABLE ${ref} DROP FOREIGN KEY ${d.quote(op.name)}`]
        : [`ALTER TABLE ${ref} DROP CONSTRAINT ${d.quote(op.name)}`]
    case 'renameTable': {
      const to = required(op.to, 'New table name')
      if (engine === 'mysql') return [`RENAME TABLE ${ref} TO ${tableRef(d, change.schema, to)}`]
      if (engine === 'mssql') return [`EXEC sp_rename ${nlit(`${change.schema}.${change.table}`)}, ${nlit(to)}`]
      return [`ALTER TABLE ${ref} RENAME TO ${d.quote(to)}`]
    }
  }
}

/**
 * Dependencies first: a foreign key can pin an index (MySQL), an index can pin a column,
 * and new indexes or keys may point at columns added in the same change.
 */
const OP_ORDER: Record<SchemaOp['op'], number> = {
  createTable: 0,
  dropForeignKey: 1,
  dropIndex: 2,
  dropColumn: 3,
  alterColumn: 4,
  addColumn: 5,
  addIndex: 6,
  addForeignKey: 7,
  renameTable: 8
}

export function schemaChangeSql(engine: Engine, change: SchemaChange): string[] {
  const d = dialectFor(engine)
  const ops = [...change.ops].sort((a, b) => OP_ORDER[a.op] - OP_ORDER[b.op])
  return ops.flatMap((op) => opSql(engine, d, change, op))
}

/**
 * SQL for an admin action. With `mask`, secrets are replaced so the preview
 * can be shown on screen; the real statements are built only when applying.
 */
export function adminSql(engine: Engine, action: AdminAction, mask: boolean): string[] {
  const d = dialectFor(engine)
  const label = ENGINES[engine].label
  switch (action.kind) {
    case 'schemaChange':
      return schemaChangeSql(engine, action.change)
    case 'dropObject':
      return [`DROP ${action.objectType === 'view' ? 'VIEW' : 'TABLE'} ${tableRef(d, action.schema, action.name)}`]
    case 'truncateTable':
      // SQLite has no TRUNCATE; an unqualified DELETE is its fast path.
      return engine === 'sqlite'
        ? [`DELETE FROM ${tableRef(d, action.schema, action.name)}`]
        : engine === 'cassandra'
          ? [`TRUNCATE ${tableRef(d, action.schema, action.name)}`]
          : [`TRUNCATE TABLE ${tableRef(d, action.schema, action.name)}`]
    case 'createUser': {
      const name = required(action.name, 'User name')
      const password = mask ? MASK : action.password
      switch (engine) {
        case 'mysql':
          return [`CREATE USER ${lit(name)}@${lit(action.host?.trim() || '%')} IDENTIFIED BY ${lit(password)}`]
        case 'postgres': {
          const attrs = [
            action.login === false ? 'NOLOGIN' : 'LOGIN',
            action.superuser ? 'SUPERUSER' : '',
            action.createDb ? 'CREATEDB' : '',
            action.createRole ? 'CREATEROLE' : ''
          ].filter(Boolean)
          if (action.password) attrs.push(`PASSWORD ${lit(password)}`)
          return [`CREATE ROLE ${d.quote(name)} WITH ${attrs.join(' ')}`]
        }
        case 'mssql':
          // A server login plus a user for it in the current database.
          return [`CREATE LOGIN ${d.quote(name)} WITH PASSWORD = ${nlit(password)}`, `CREATE USER ${d.quote(name)} FOR LOGIN ${d.quote(name)}`]
        case 'clickhouse':
          return [`CREATE USER ${d.quote(name)} IDENTIFIED BY ${lit(password)}`]
        default:
          throw new Error(`Creating users is not available for ${label}.`)
      }
    }
    case 'dropUser':
      switch (engine) {
        case 'mysql':
          return [`DROP USER ${lit(action.name)}@${lit(action.host ?? '%')}`]
        case 'postgres':
          return [`DROP ROLE ${d.quote(action.name)}`]
        case 'mssql':
          return [`DROP USER IF EXISTS ${d.quote(action.name)}`, `DROP LOGIN ${d.quote(action.name)}`]
        case 'clickhouse':
          return [`DROP USER ${d.quote(action.name)}`]
        default:
          throw new Error(`Dropping users is not available for ${label}.`)
      }
  }
}
