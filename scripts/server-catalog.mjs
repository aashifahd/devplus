// Regenerate src/shared/serverCatalog.ts: the server versions DevPlus can install, with
// download URLs from official hosts and the SHA-256 each download must match.
//   node scripts/server-catalog.mjs [cacheDir]
// MariaDB publishes checksums; PostgreSQL (EDB) and MySQL archives are downloaded once here
// and hashed, so a tampered or truncated download on a user's machine is rejected.
import { createHash } from 'node:crypto'
import { createReadStream, createWriteStream, existsSync, mkdirSync, renameSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Readable } from 'node:stream'
import { pipeline } from 'node:stream/promises'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const cache = process.argv[2] ?? join(root, '.server-cache')
mkdirSync(cache, { recursive: true })

const POSTGRES = ['18.6', '17.11', '16.15']
const MYSQL = [
  { version: '8.4.11', channel: 'LTS' },
  { version: '9.7.2', channel: 'LTS' },
  { version: '26.7.0', channel: 'Innovation' }
]
const MARIADB_SERIES = ['12.3', '11.8', '11.4', '10.11']

async function sha256OfUrl(url, file) {
  const path = join(cache, file)
  if (!existsSync(path)) {
    const res = await fetch(url)
    if (!res.ok || !res.body) throw new Error(`${url}: HTTP ${res.status}`)
    await pipeline(Readable.fromWeb(res.body), createWriteStream(`${path}.part`))
    renameSync(`${path}.part`, path)
  }
  const hash = createHash('sha256')
  await pipeline(createReadStream(path), hash)
  return hash.digest('hex')
}

async function size(url) {
  const res = await fetch(url, { method: 'HEAD' })
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
  return Number(res.headers.get('content-length') ?? 0)
}

const entries = []

for (const v of POSTGRES) {
  const file = `postgresql-${v}-1-windows-x64-binaries.zip`
  const url = `https://get.enterprisedb.com/postgresql/${file}`
  console.log('postgres', v)
  entries.push({ engine: 'postgres', version: v, channel: v === POSTGRES[0] ? 'Latest' : 'Supported', platform: 'win32-x64', url, file, bytes: await size(url), sha256: await sha256OfUrl(url, file) })
}

for (const { version, channel } of MYSQL) {
  const series = version.split('.').slice(0, 2).join('.')
  const file = `mysql-${version}-winx64.zip`
  const url = `https://cdn.mysql.com/Downloads/MySQL-${series}/${file}`
  console.log('mysql', version)
  entries.push({ engine: 'mysql', version, channel, platform: 'win32-x64', url, file, bytes: await size(url), sha256: await sha256OfUrl(url, file) })
}

for (const series of MARIADB_SERIES) {
  const data = await (await fetch(`https://downloads.mariadb.org/rest-api/mariadb/${series}/latest/`)).json()
  for (const [version, rel] of Object.entries(data.releases)) {
    const f = rel.files.find((x) => x.os === 'Windows' && x.file_name.endsWith('winx64.zip'))
    if (!f) continue
    const url = `https://archive.mariadb.org/mariadb-${version}/winx64-packages/${f.file_name}`
    console.log('mariadb', version)
    entries.push({ engine: 'mariadb', version, channel: 'LTS', platform: 'win32-x64', url, file: f.file_name, bytes: await size(url), sha256: f.checksum.sha256sum })
  }
}

const out = `// Generated by scripts/server-catalog.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
import type { ServerRelease } from './servers'

export const SERVER_CATALOG: ServerRelease[] = ${JSON.stringify(entries, null, 2)}
`
writeFileSync(join(root, 'src', 'shared', 'serverCatalog.ts'), out)
console.log(`wrote ${entries.length} releases to src/shared/serverCatalog.ts`)
